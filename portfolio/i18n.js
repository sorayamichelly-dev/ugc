const TITULO = { pt: 'Soraya Oliveira UGC', en: 'Soraya Oliveira · UGC Creator' };

const ALVOS = 'h1,h2,h3,p,li,dt,dd,span,a,button,blockquote,figcaption,small';
const original = new Map();

const normalizar = (s) => s.replace(/\s+/g, ' ').trim();

function marcar() {
  document.querySelectorAll(ALVOS).forEach((el) => {
    // se um ancestral ja foi marcado, o texto dele sera trocado inteiro
    if (el.parentElement && el.parentElement.closest('[data-i18n]')) return;
    const chave = normalizar(el.innerHTML);
    if (Object.prototype.hasOwnProperty.call(EN, chave)) {
      original.set(el, el.innerHTML);
      el.setAttribute('data-i18n', chave);
    }
  });
}

function aplicar(idioma) {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const chave = el.getAttribute('data-i18n');
    el.innerHTML = idioma === 'en' ? EN[chave] : original.get(el);
  });

  document.documentElement.lang = idioma === 'en' ? 'en' : 'pt-BR';
  document.title = TITULO[idioma] || TITULO.pt;

  document.querySelectorAll('.idioma button').forEach((b) => {
    const ativo = b.dataset.lang === idioma;
    b.classList.toggle('on', ativo);
    b.setAttribute('aria-pressed', ativo ? 'true' : 'false');
  });

  try { localStorage.setItem('idioma', idioma); } catch (e) {}
}

function idiomaInicial() {
  let salvo = null;
  try { salvo = localStorage.getItem('idioma'); } catch (e) {}
  if (salvo === 'pt' || salvo === 'en') return salvo;
  const navegador = (navigator.language || navigator.userLanguage || 'pt').toLowerCase();
  return navegador.startsWith('pt') ? 'pt' : 'en';
}

marcar();
document.querySelectorAll('.idioma button').forEach((b) => {
  b.addEventListener('click', () => aplicar(b.dataset.lang));
});
aplicar(idiomaInicial());
